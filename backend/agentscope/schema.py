"""Standardised AgentScope event schema.

Every adapter translates framework-specific telemetry into `Event`. The engine
never needs to know which framework produced an event.
"""
from __future__ import annotations

import uuid
from datetime import datetime, timezone
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field

EventType = Literal[
    "agent_lifecycle",
    "task",
    "tool_execution",
    "llm_call",
    "delegation",
    "message",
    "reasoning",
    "file_operation",
    "network",
    "process",
    "system",
    "error",
]

Status = Literal["pending", "running", "completed", "failed", "blocked", "info"]
Risk = Literal["info", "low", "medium", "high", "critical"]

# How much we actually know about an event. The UI must never blur these.
#   exposed_reasoning - progress summaries / thoughts the framework chose to expose
#   tool_call         - a tool call reported by the framework (what the agent asked for)
#   execution         - observed execution (container API, process table, wire metadata)
#   inferred          - derived by AgentScope heuristics (e.g. URL found inside a script)
#   simulated         - generated by the built-in simulator
Evidence = Literal["exposed_reasoning", "tool_call", "execution", "inferred", "simulated"]

CATEGORIES = (
    "web", "api", "terminal", "python", "file_read", "file_write", "file_delete",
    "subprocess", "delegation", "message", "database", "llm", "reasoning", "task",
    "memory", "network", "system", "tool", "error",
)

ACTION_CATEGORY = {
    "browser_navigation": "web", "web_search": "web", "browser_action": "web",
    "http_request": "api", "api_call": "api", "mcp_call": "api",
    "terminal_command": "terminal", "shell_command": "terminal",
    "python_execution": "python", "code_execution": "python", "nodejs_execution": "python",
    "file_read": "file_read", "directory_access": "file_read",
    "file_write": "file_write", "file_create": "file_write", "file_modify": "file_write",
    "file_delete": "file_delete",
    "process_spawn": "subprocess", "process_exit": "subprocess",
    "delegate_task": "delegation", "agent_message": "message",
    "database_query": "database",
    "llm_call": "llm", "reasoning": "reasoning",
    "task_received": "task", "task_completed": "task", "task_failed": "task",
    "memory_op": "memory",
    "network_connection": "network", "dns_lookup": "network",
    "container_state": "system", "status": "system",
}


def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="milliseconds")


def iso_to_ts(value: str) -> float:
    try:
        return datetime.fromisoformat(value.replace("Z", "+00:00")).timestamp()
    except Exception:
        return datetime.now(timezone.utc).timestamp()


def ts_to_iso(ts: float) -> str:
    return datetime.fromtimestamp(ts, timezone.utc).isoformat(timespec="milliseconds")


class Event(BaseModel):
    model_config = ConfigDict(extra="ignore")

    # --- core schema (matches the specification) ---
    event_id: str = Field(default_factory=lambda: uuid.uuid4().hex)
    timestamp: str = Field(default_factory=now_iso)
    agent_id: str
    parent_agent_id: str | None = None
    event_type: EventType
    action: str
    target: str | None = None
    tool: str | None = None
    status: Status = "completed"
    duration_ms: float | None = None
    metadata: dict[str, Any] = Field(default_factory=dict)
    source: str

    # --- extensions ---
    instance_id: str | None = None
    agent_name: str | None = None
    category: str | None = None
    evidence: Evidence = "tool_call"
    risk: Risk = "info"
    task_id: str | None = None
    parent_event_id: str | None = None
    input: str | None = None
    output: str | None = None

    def derive_category(self) -> str:
        if self.category:
            return self.category
        if self.action in ACTION_CATEGORY:
            return ACTION_CATEGORY[self.action]
        return {
            "error": "error", "llm_call": "llm", "delegation": "delegation",
            "message": "message", "reasoning": "reasoning", "task": "task",
            "network": "network", "process": "subprocess", "system": "system",
        }.get(self.event_type, "tool")

    @property
    def ts(self) -> float:
        return iso_to_ts(self.timestamp)


class Agent(BaseModel):
    agent_id: str
    name: str
    parent_agent_id: str | None = None
    source: str
    instance_id: str | None = None
    status: str = "idle"
    current_task: str | None = None
    current_tool: str | None = None
    model: str | None = None
    tokens_in: int = 0
    tokens_out: int = 0
    context_pct: float | None = None
    first_seen: float
    last_seen: float
    event_count: int = 0
    kind: str = "agent"  # agent | container | system
    metadata: dict[str, Any] = Field(default_factory=dict)
