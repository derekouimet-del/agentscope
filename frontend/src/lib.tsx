export function agentColor(id: string): string {
  let h = 0
  for (let i = 0; i < id.length; i++) h = (h * 31 + id.charCodeAt(i)) >>> 0
  return `hsl(${h % 360} 75% 62%)`
}

export function shortAgent(id: string, name?: string | null): string {
  if (name) return name.length > 34 ? name.slice(0, 33) + '…' : name
  return id.split(':').slice(-1)[0]
}

export function fmtTime(ts: number, withMs = false): string {
  const d = new Date(ts * 1000)
  const t = d.toLocaleTimeString([], { hour12: false })
  return withMs ? `${t}.${String(d.getMilliseconds()).padStart(3, '0')}` : t
}
export const fmtDateTime = (ts: number) => new Date(ts * 1000).toLocaleString([], { hour12: false })
export function fmtAgo(ts: number): string {
  const s = Date.now() / 1000 - ts
  if (s < 5) return 'just now'
  if (s < 60) return `${Math.round(s)}s ago`
  if (s < 3600) return `${Math.round(s / 60)}m ago`
  if (s < 86400) return `${(s / 3600).toFixed(1)}h ago`
  return `${Math.round(s / 86400)}d ago`
}
export function fmtDur(ms: number | null | undefined): string {
  if (ms === null || ms === undefined) return '—'
  if (ms < 1000) return `${Math.round(ms)}ms`
  if (ms < 60000) return `${(ms / 1000).toFixed(1)}s`
  return `${Math.floor(ms / 60000)}m ${Math.round((ms % 60000) / 1000)}s`
}
export function fmtBytes(n: number | null | undefined): string {
  if (n === null || n === undefined) return '—'
  const u = ['B', 'KB', 'MB', 'GB', 'TB']; let i = 0
  while (n >= 1024 && i < u.length - 1) { n /= 1024; i++ }
  return `${n.toFixed(i ? 1 : 0)} ${u[i]}`
}

export function statusAt(e: AEvent, cursor: number | null): string {
  if (cursor === null) return e.status
  if (e.status === 'running') return 'running'
  if (e.duration_ms && e.ts! + e.duration_ms / 1000 > cursor) return 'running'
  return e.status
}

