export function eventLabel(e: AEvent): string {
  const t = e.target ? (e.target.length > 80 ? e.target.slice(0, 79) + '…' : e.target) : ''
  return `${e.action.replace(/_/g, ' ')}${t ? ' · ' + t : ''}`
}
